async function main() {
  const dryRun = process.argv.includes("--dry-run");
  const rows = await db.query.products.findMany({});
  const targets = rows.filter(
    (r) => r.isVisible && !r.deletedAt && (!r.description || r.description.trim() === ""),
  );
  console.log(`Кандидатов: ${targets.length}${dryRun ? " (dry-run)" : ""}\n`);

  const patches: { id: number; name: string; description: string }[] = [];
  const unmatched: string[] = [];
  for (const p of targets) {
    const rule = rules.find((r) => r.match(p.name));
    if (!rule) {
      unmatched.push(`#${p.id}  ${p.name}`);
      continue;
    }
    patches.push({ id: p.id, name: p.name, description: rule.build(p.name) });
  }

  console.log(`Готово к записи: ${patches.length}`);
  console.log(`Без совпадения правил: ${unmatched.length}`);
  for (const u of unmatched) console.log(`  · ${u}`);
  console.log();

  if (!dryRun && patches.length) {
    const ids = patches.map((p) => p.id);
    const now = new Date();
    for (const p of patches) {
      await db
        .update(products)
        .set({ description: p.description, updatedAt: now })
        .where(eq(products.id, p.id));
    }
    console.log(`Обновлено: ${ids.length}`);
  } else if (dryRun) {
    for (const p of patches.slice(0, 4)) {
      console.log(`--- #${p.id}  ${p.name}\n${p.description}\n`);
    }
  }
  void inArray;
}
main().then(() => process.exit(0)).catch((e) => { console.error(e); process.exit(1); });
