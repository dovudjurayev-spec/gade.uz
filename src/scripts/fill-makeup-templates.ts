async function main() {
  const rows = await db
    .select({ id: products.id, name: products.name })
    .from(products)
    .where(
      and(
        eq(products.categoryId, 6),
        isNull(products.deletedAt),
        or(isNull(products.description), sql`length(${products.description}) = 0`),
      ),
    );

  const counts: Record<string, number> = {};
  const misses: string[] = [];
  let updated = 0;

  for (const p of rows) {
    const rule = rules.find((r) => r.match.test(p.name));
    if (!rule) {
      misses.push(p.name);
      continue;
    }
    counts[rule.description.slice(0, 40)] = (counts[rule.description.slice(0, 40)] ?? 0) + 1;
    await db.update(products).set({ description: rule.description, updatedAt: new Date() }).where(eq(products.id, p.id));
    updated++;
  }

  console.log(`UPDATED: ${updated}`);
  console.log(`MISSED:  ${misses.length}`);
  if (misses.length) {
    console.log("\nUnmatched product names:");
    for (const m of misses.slice(0, 50)) console.log("  -", m);
    if (misses.length > 50) console.log(`  … (+${misses.length - 50} more)`);
  }
}

main().then(() => process.exit(0)).catch((e) => { console.error(e); process.exit(1); });
