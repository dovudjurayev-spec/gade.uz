    const [res] = await db
      .update(products)
      .set({ description: u.description, updatedAt: new Date() })
      .where(eq(products.id, u.id))
      .returning({ id: products.id, name: products.name });
    console.log(res ? `OK  ${res.id}  ${res.name}` : `MISS id=${u.id}`);
